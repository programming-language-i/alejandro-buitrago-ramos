def suma(valor1, valor2):
    return valor1 + valor2

def resta(valor1, valor2):
    return valor1 - valor2

def multi(valor1, valor2):
    return valor1 * valor2

resulado_suma = suma(5, 2)
resulado_resta = resta(5, 2)
resulado_multi = multi(5, 2)

print (f"Resultado suma: {resulado_suma}")
print (f"Resultado resta: {resulado_resta}")
print (f"Resultado multi: {resulado_multi}")

